"""One offline eSpeak NG request; all output is synthetic mono PCM16 at 16 kHz."""
from array import array
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import sys
import wave

LABEL = b"Synthetic voice generated by eSpeak NG for VOLPAROSSA.\0"
RATE = 16000


def require(ok):
    if not ok:
        raise ValueError("speech synthesis")


def chunk(name, data):
    return name + struct.pack("<I", len(data)) + data + b"\0" * (len(data) % 2)


def convert(source):
    with wave.open(str(source), "rb") as wav:
        frames = wav.getnframes()
        require(wav.getnchannels() == 1 and wav.getsampwidth() == 2 and wav.getframerate() == 22050
                and wav.getcomptype() == "NONE" and 0 < frames <= 30 * 22050)
        samples = array("h")
        samples.frombytes(wav.readframes(frames))
    require(len(samples) == frames and sys.byteorder == "little")
    pcm = array("h")
    for i in range(frames * RATE // 22050):
        left, fraction = divmod(i * 22050, RATE)
        right = min(left + 1, frames - 1)
        pcm.append((samples[left] * (RATE - fraction) + samples[right] * fraction) // RATE)
    content = (b"WAVE" + chunk(b"fmt ", struct.pack("<HHIIHH", 1, 1, RATE, RATE * 2, 2, 16))
               + chunk(b"LIST", b"INFO" + chunk(b"ICMT", LABEL)) + chunk(b"data", pcm.tobytes()))
    return chunk(b"RIFF", content), len(pcm)


def main():
    identifier = "0" * 32
    try:
        require(os.geteuid() != 0)
        os.umask(0o077)
        raw = sys.stdin.buffer.readline(4097)
        require(raw.endswith(b"\n") and len(raw) <= 4096)
        request = json.loads(raw)
        require(set(request) == {"version", "id", "voice", "text"} and request["version"] == 1
                and re.fullmatch("[a-f0-9]{32}", request["id"]) and request["voice"] in ("nl", "en-us")
                and 0 < len(request["text"].encode()) <= 512)
        identifier = request["id"]
        source = Path("/tmp/synth.wav")
        subprocess.run(["/usr/bin/espeak-ng", "-b", "1", "-v", request["voice"], "-s", "145",
                        "-w", str(source), "--stdin"], input=request["text"].encode(), check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        data, count = convert(source)
        with Path("/output/audio.wav").open("xb") as out:
            out.write(data)
    except (KeyError, TypeError, ValueError, OSError, EOFError, wave.Error, subprocess.SubprocessError):
        print(json.dumps(dict(version=1, id=identifier, kind="result", status="error", code="SPEECH_SYNTHESIS_FAILED")), flush=True)
        return 1
    print(json.dumps(dict(version=1, id=identifier, kind="result", status="ok",
                          voice=request["voice"], audio_samples=count)), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
