"""Exercise private synthesis and compare PCM with direct, independently generated references."""
import hashlib
import json
import os
from pathlib import Path
import re
import runpy
import subprocess
import sys

FIXTURE = runpy.run_path(str(Path(__file__).with_name("speech-recognition-fixture.py")))
CLI = "/home/vpci/target/debug/volparossa"
LABEL = b"Synthetic voice generated by eSpeak NG for VOLPAROSSA.\0"


def require(value):
    if not value:
        raise ValueError("speech synthesis fixture")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def generate(root, references, output, revision):
    require(os.geteuid() != 0 and subprocess.check_output(["systemd-detect-virt", "--vm"]).strip() == b"kvm")
    directory = root / "synthesis"
    directory.mkdir(mode=0o700)
    records = {}
    for name, phrase in {**FIXTURE["PHRASES"], "dutch": "De trein vertrekt morgen om negen uur."}.items():
        voice = "nl" if name == "dutch" else "en-us"
        if name == "dutch":
            raw = directory / "native.wav"
            subprocess.run(["/usr/bin/espeak-ng", "-v", voice, "-s", "145", "-w", raw, phrase],
                           check=True, timeout=10)
            original_pcm = FIXTURE["to_16k"](FIXTURE["original_wave"](raw, 22050))
        else:
            original_pcm = FIXTURE["original_wave"](references / (name + ".wav"), 16000)
        text = directory / (name + ".txt")
        text.write_text(phrase)
        text.chmod(0o600)
        wave = directory / (name + ".wav")
        command = [CLI, "compute", "synthesize", "--input", text, "--output", wave, "--voice", voice]
        preview = json.loads(subprocess.check_output(command, timeout=5))
        require(preview["execute"] is False and not wave.exists())
        result = json.loads(subprocess.check_output([*command, "--execute"], timeout=25))
        pcm = FIXTURE["original_wave"](wave, 16000)
        data = wave.read_bytes()
        require(pcm == original_pcm and result["audio_samples"] == len(pcm) // 2 and result["synthetic"] is True
                and result["engine"] == "espeak-ng" and result["voice"] == voice and result["sample_rate"] == 16000
                and result["cleanup"] == {"complete": True} and wave.stat().st_mode & 0o777 == 0o600
                and LABEL in data and not list(directory.glob(".volparossa-speech-*")))
        attempt = subprocess.run([*command, "--execute"], capture_output=True, timeout=5)
        require(attempt.returncode != 0 and not attempt.stdout and b"compute_synthesis_output_exists" in attempt.stderr
                and wave.read_bytes() == data)
        records[name] = {"original_pcm_sha256": digest(original_pcm), "rendered_pcm_sha256": digest(pcm),
                         "marked_wav_sha256": digest(data), "samples": len(pcm) // 2, "cli": result,
                         "unchanged_after_second_write": True, "marker_present": True}
    proof = {"version": 1, "source_revision": revision, "clips": records, "passed": True}
    (output / "speech-synthesis-smoke.json").write_text(json.dumps(proof, sort_keys=True) + "\n")
    return directory


def verify(directory, revision):
    proof = FIXTURE["load"](directory / "speech-synthesis-smoke.json")
    require(re.fullmatch("[a-f0-9]{40}", revision) and proof["version"] == 1 and proof["source_revision"] == revision
            and proof["passed"] is True and set(proof["clips"]) == {"dutch", *FIXTURE["PHRASES"]})
    for name, row in proof["clips"].items():
        response = row["cli"]
        require(re.fullmatch("[a-f0-9]{64}", row["original_pcm_sha256"])
                and row["original_pcm_sha256"] == row["rendered_pcm_sha256"]
                and re.fullmatch("[a-f0-9]{64}", row["marked_wav_sha256"])
                and row["unchanged_after_second_write"] is True and row["marker_present"] is True
                and type(row["samples"]) is int and 0 < row["samples"] <= 480000
                and response["operation"] == "compute_synthesize" and response["version"] == 1
                and response["execute"] is True and response["synthetic"] is True and response["sample_rate"] == 16000
                and response["engine"] == "espeak-ng" and response["voice"] == ("nl" if name == "dutch" else "en-us")
                and response["audio_samples"] == row["samples"] and response["cleanup"]["complete"] is True)
        if name in FIXTURE["PHRASES"]:
            original = FIXTURE["load"](directory / ("speech-" + name + ".json"))
            require(original["operation"] == "compute_transcribe" and original["audio_samples"] == row["samples"])


if __name__ == "__main__":
    verify(Path(sys.argv[1]), sys.argv[2])
