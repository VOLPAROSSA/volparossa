/// Versioned request sent from the unprivileged Rust agent to the isolated native process.
#[derive(Clone, PartialEq, Message)]
pub struct NativeRequest {
    /// Must equal [`NATIVE_API_VERSION`].
    #[prost(uint32, tag = "1")]
    pub api_version: u32,
    /// Per-request nonce generated by the agent; echoed in the response.
    #[prost(bytes = "vec", tag = "2")]
    pub request_nonce: Vec<u8>,
    /// Exact process instance selected by preflight; empty only for preflight itself.
    #[prost(bytes = "vec", tag = "3")]
    pub target_native_instance_id: Vec<u8>,
    /// Strict allowlist of native operations.
    #[prost(
        oneof = "native_request::Operation",
        tags = "10, 11, 12, 13, 14, 15, 16, 17, 18"
    )]
    pub operation: Option<native_request::Operation>,
}

/// Native request operation variants.
pub mod native_request {
    use prost::Oneof;

    use super::{
        AddPath, GetStatus, Preflight, ReceiveDatagram, RemovePath, SendDatagram, StartExitSession,
        StartSession, StopSession,
    };

    /// Exactly one typed native operation.
    #[derive(Clone, PartialEq, Oneof)]
    pub enum Operation {
        /// Establishes one outer MASQUE/MPQUIC session without paths yet.
        #[prost(message, tag = "10")]
        StartSession(StartSession),
        /// Adds one WireGuard-bound QUIC path.
        #[prost(message, tag = "11")]
        AddPath(AddPath),
        /// Removes one existing QUIC path.
        #[prost(message, tag = "12")]
        RemovePath(RemovePath),
        /// Passes one already-authorised inner IP datagram to CONNECT-IP.
        #[prost(message, tag = "13")]
        SendDatagram(SendDatagram),
        /// Requests bounded per-path status.
        #[prost(message, tag = "14")]
        GetStatus(GetStatus),
        /// Closes and wipes one native session.
        #[prost(message, tag = "15")]
        StopSession(StopSession),
        /// Polls one bounded reverse inner IP datagram.
        #[prost(message, tag = "16")]
        ReceiveDatagram(ReceiveDatagram),
        /// Authorises one short-lived route on an explicitly enabled exit.
        #[prost(message, tag = "17")]
        StartExitSession(StartExitSession),
        /// Obtains the role and fresh per-start identity of one native process.
        #[prost(message, tag = "18")]
        Preflight(Preflight),
    }
}

