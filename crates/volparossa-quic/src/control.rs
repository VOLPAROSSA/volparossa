    #[test]
    fn reverse_response_round_trips_and_can_be_wiped() {
        let mut response = NativeResponse {
            api_version: NATIVE_API_VERSION,
            request_nonce: vec![5; 16],
            result: NativeResultCode::Ok as i32,
            diagnostic_code: "datagram".to_owned(),
            paths: Vec::new(),
            received_datagram: Some(ReceivedDatagram {
                route_context_id: vec![1; 16],
                masque_context_id: 9,
                inner_ip_packet: ipv4_packet(),
            }),
            process_identity: Some(NativeProcessIdentity {
                role: NativeProcessRole::Client as i32,
                native_instance_id: vec![9; 32],
            }),
            request_sha256: vec![8; 32],
            tunnel_assignment: None,
        };
        let frame = encode_response(&response).expect("response encode");
        response
            .received_datagram
            .as_mut()
            .expect("datagram")
            .wipe();
        assert!(
            response
                .received_datagram
                .as_ref()
                .expect("datagram")
                .inner_ip_packet
                .is_empty()
        );
        let decoded = decode_response(&frame[4..]).expect("response decode");
        assert_eq!(
            decoded
                .received_datagram
                .as_ref()
                .expect("decoded datagram")
                .masque_context_id,
            9
        );

        let mut overflow = decoded;
        overflow.result = NativeResultCode::QueueOverflow as i32;
        assert!(encode_response(&overflow).is_err());
        overflow.received_datagram = None;
        assert!(encode_response(&overflow).is_ok());
    }
