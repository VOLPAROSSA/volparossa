/// Fail-closed frame/validation errors.
#[derive(Debug, Error)]
pub enum ControlError {
    /// Async local socket I/O failed.
    #[error("native control I/O failed: {0}")]
    Io(#[from] std::io::Error),
    /// Protobuf payload is malformed.
    #[error("native control protobuf is malformed: {0}")]
    Decode(#[from] prost::DecodeError),
    /// Frame exceeds the fixed local limit.
    #[error("native control frame exceeds {MAX_CONTROL_FRAME} bytes")]
    TooLarge,
    /// Message violates a structural security rule.
    #[error("invalid native control message: {0}")]
    Invalid(&'static str),
}

/// Encodes and length-prefixes a validated native request.
///
/// # Errors
///
/// Returns an error when request validation fails or the encoded frame exceeds the hard limit.
pub fn encode_request(request: &NativeRequest) -> Result<Vec<u8>, ControlError> {
    validate_request(request)?;
    encode_frame(request)
}

/// Computes the v6 response-correlation digest of one canonical unframed request.
///
/// # Errors
///
/// Returns an error when the request is invalid or its canonical payload exceeds the frame bound.
pub fn request_sha256(request: &NativeRequest) -> Result<[u8; SHA256_LEN], ControlError> {
    validate_request(request)?;
    let payload = zeroize::Zeroizing::new(request.encode_to_vec());
    if payload.is_empty() || payload.len() > MAX_CONTROL_FRAME {
        return Err(ControlError::TooLarge);
    }
    let payload_len = u32::try_from(payload.len()).map_err(|_| ControlError::TooLarge)?;
    let mut hasher = Sha256::new();
    hasher.update(NATIVE_REQUEST_DIGEST_DOMAIN);
    hasher.update(payload_len.to_be_bytes());
    hasher.update(payload.as_slice());
    Ok(hasher.finalize().into())
}

/// Encodes and length-prefixes a validated native response.
///
/// # Errors
///
/// Returns an error when response validation fails or the encoded frame exceeds the hard limit.
pub fn encode_response(response: &NativeResponse) -> Result<Vec<u8>, ControlError> {
    validate_response(response)?;
    encode_frame(response)
}

/// Decodes one already-unframed request payload.
///
/// # Errors
///
/// Returns an error for oversized, malformed, or semantically invalid request bytes.
pub fn decode_request(bytes: &[u8]) -> Result<NativeRequest, ControlError> {
    if bytes.len() > MAX_CONTROL_FRAME {
        return Err(ControlError::TooLarge);
    }
    let request = NativeRequest::decode(bytes)?;
    validate_request(&request)?;
    let canonical = zeroize::Zeroizing::new(request.encode_to_vec());
    if canonical.as_slice() != bytes {
        return Err(ControlError::Invalid("non-canonical request encoding"));
    }
    Ok(request)
}

/// Decodes one already-unframed response payload.
///
/// # Errors
///
/// Returns an error for oversized, malformed, or semantically invalid response bytes.
pub fn decode_response(bytes: &[u8]) -> Result<NativeResponse, ControlError> {
    if bytes.len() > MAX_CONTROL_FRAME {
        return Err(ControlError::TooLarge);
    }
    let response = NativeResponse::decode(bytes)?;
    validate_response(&response)?;
    let canonical = zeroize::Zeroizing::new(response.encode_to_vec());
    if canonical.as_slice() != bytes {
        return Err(ControlError::Invalid("non-canonical response encoding"));
    }
    Ok(response)
}

/// Reads one bounded length-prefixed request.
///
/// # Errors
///
/// Returns an error when the stream cannot be read or its frame is empty, oversized, malformed,
/// or semantically invalid.
pub async fn read_request<R>(reader: &mut R) -> Result<NativeRequest, ControlError>
where
    R: AsyncRead + Unpin,
{
    let mut payload = read_frame(reader).await?;
    let result = decode_request(&payload);
    payload.zeroize();
    result
}

/// Reads one bounded length-prefixed response.
///
/// # Errors
///
/// Returns an error when the stream cannot be read or its frame is empty, oversized, malformed,
/// or semantically invalid.
pub async fn read_response<R>(reader: &mut R) -> Result<NativeResponse, ControlError>
where
    R: AsyncRead + Unpin,
{
    let mut payload = read_frame(reader).await?;
    let result = decode_response(&payload);
    payload.zeroize();
    result
}

fn encode_frame<M: Message>(message: &M) -> Result<Vec<u8>, ControlError> {
    let encoded_len = message.encoded_len();
    if encoded_len > MAX_CONTROL_FRAME {
        return Err(ControlError::TooLarge);
    }
    let length = u32::try_from(encoded_len).map_err(|_| ControlError::TooLarge)?;
    let mut frame = Vec::with_capacity(4 + encoded_len);
    frame.extend_from_slice(&length.to_be_bytes());
    message
        .encode(&mut frame)
        .map_err(|_| ControlError::TooLarge)?;
    Ok(frame)
}

async fn read_frame<R>(reader: &mut R) -> Result<Vec<u8>, ControlError>
where
    R: AsyncRead + Unpin,
{
    let length = reader.read_u32().await?;
    let length = usize::try_from(length).map_err(|_| ControlError::TooLarge)?;
    if length == 0 {
        return Err(ControlError::Invalid("empty frame"));
    }
    if length > MAX_CONTROL_FRAME {
        return Err(ControlError::TooLarge);
    }
    let mut payload = vec![0_u8; length];
    reader.read_exact(&mut payload).await?;
    Ok(payload)
}

fn validate_request(request: &NativeRequest) -> Result<(), ControlError> {
    use native_request::Operation;

    if request.api_version != NATIVE_API_VERSION {
        return Err(ControlError::Invalid("unsupported API version"));
    }
    if request.request_nonce.len() != 16 || request.request_nonce.iter().all(|byte| *byte == 0) {
        return Err(ControlError::Invalid(
            "request nonce must be a non-zero 16-byte value",
        ));
    }
    let operation = request
        .operation
        .as_ref()
        .ok_or(ControlError::Invalid("missing operation"))?;
    if matches!(operation, Operation::Preflight(_)) {
        if !request.target_native_instance_id.is_empty() {
            return Err(ControlError::Invalid(
                "preflight must not target a native process instance",
            ));
        }
    } else {
        validate_native_instance_id(&request.target_native_instance_id)?;
    }
    match operation {
        Operation::Preflight(value) => {
            validate_native_role(value.expected_role)?;
        }
        Operation::StartSession(value) => {
            validate_context(&value.route_context_id)?;
            if value.exit_spki_sha256.len() != 32
                || value.exit_spki_sha256.iter().all(|byte| *byte == 0)
            {
                return Err(ControlError::Invalid(
                    "SPKI pin must be a non-zero 32-byte value",
                ));
            }
            validate_session_shape(
                value.minimum_paths,
                value.masque_context_id,
                value.transport_mode,
            )?;
            validate_auth_secret(&value.auth_secret)?;
            validate_tls_server_name(&value.tls_server_name)?;
            validate_expiry(value.expires_at_ms)?;
            validate_signed_route_fields(
                &value.reservation_id,
                &value.finalize_id,
                &value.auth_secret,
                &value.auth_commitment,
                &value.certificate_sha256,
                &value.client_native_instance_id,
                &value.exit_native_instance_id,
            )?;
            if value.client_native_instance_id != request.target_native_instance_id {
                return Err(ControlError::Invalid(
                    "client start does not target its signed native instance",
                ));
            }
        }
        Operation::StartExitSession(value) => {
            validate_start_exit(value)?;
            if value.exit_native_instance_id != request.target_native_instance_id {
                return Err(ControlError::Invalid(
                    "exit start does not target its signed native instance",
                ));
            }
        }
        Operation::AddPath(value) => {
            validate_add_path(value)?;
        }
        Operation::RemovePath(value) => {
            validate_context(&value.route_context_id)?;
            if value.path_id == 0 || value.path_id > 8 {
                return Err(ControlError::Invalid("invalid path ID"));
            }
        }
        Operation::SendDatagram(value) => {
            validate_context(&value.route_context_id)?;
            validate_masque_context(value.masque_context_id)?;
            validate_ip_packet(&value.inner_ip_packet)?;
        }
        Operation::GetStatus(value) => validate_context(&value.route_context_id)?,
        Operation::StopSession(value) => validate_context(&value.route_context_id)?,
        Operation::ReceiveDatagram(value) => {
            validate_context(&value.route_context_id)?;
            validate_masque_context(value.masque_context_id)?;
        }
    }
    Ok(())
}

fn validate_response(response: &NativeResponse) -> Result<(), ControlError> {
    if response.api_version != NATIVE_API_VERSION
        || response.request_nonce.len() != 16
        || response.request_nonce.iter().all(|byte| *byte == 0)
    {
        return Err(ControlError::Invalid("invalid response version or nonce"));
    }
    let result = NativeResultCode::try_from(response.result)
        .map_err(|_| ControlError::Invalid("unknown native result code"))?;
    let identity = response
        .process_identity
        .as_ref()
        .ok_or(ControlError::Invalid("missing native process identity"))?;
    validate_native_role(identity.role)?;
    validate_native_instance_id(&identity.native_instance_id)?;
    if response.request_sha256.len() != SHA256_LEN {
        return Err(ControlError::Invalid("invalid request digest"));
    }
    if let Some(assignment) = response.tunnel_assignment.as_ref() {
        if result != NativeResultCode::Ok || response.received_datagram.is_some() {
            return Err(ControlError::Invalid(
                "tunnel assignment is inappropriate for this response",
            ));
        }
        validate_tunnel_assignment(assignment)?;
    }
    if response.diagnostic_code.len() > 64
        || !response
            .diagnostic_code
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-'))
    {
        return Err(ControlError::Invalid("invalid diagnostic code"));
    }
    if response.paths.len() > 8 {
        return Err(ControlError::Invalid("too many native path records"));
    }
    let mut seen_path_ids = 0_u16;
    for path in &response.paths {
        if path.path_id == 0 || path.path_id > 8 {
            return Err(ControlError::Invalid("invalid native path ID"));
        }
        let bit = 1_u16 << (path.path_id - 1);
        if seen_path_ids & bit != 0 {
            return Err(ControlError::Invalid("duplicate native path ID"));
        }
        seen_path_ids |= bit;
    }
    if let Some(datagram) = response.received_datagram.as_ref() {
        if result != NativeResultCode::Ok || !response.paths.is_empty() {
            return Err(ControlError::Invalid(
                "datagram is not valid for this response result",
            ));
        }
        validate_context(&datagram.route_context_id)?;
        validate_masque_context(datagram.masque_context_id)?;
        validate_ip_packet(&datagram.inner_ip_packet)?;
    }
    if matches!(
        result,
        NativeResultCode::NoDatagram | NativeResultCode::QueueOverflow
    ) && response.received_datagram.is_some()
    {
        return Err(ControlError::Invalid(
            "empty or overflow response carried a datagram",
        ));
    }
    Ok(())
}

fn validate_native_role(role: i32) -> Result<NativeProcessRole, ControlError> {
    match NativeProcessRole::try_from(role) {
        Ok(NativeProcessRole::Client) => Ok(NativeProcessRole::Client),
        Ok(NativeProcessRole::Exit) => Ok(NativeProcessRole::Exit),
        Ok(NativeProcessRole::Unspecified) | Err(_) => {
            Err(ControlError::Invalid("invalid native process role"))
        }
    }
}

fn validate_native_instance_id(value: &[u8]) -> Result<(), ControlError> {
    validate_nonzero_fixed::<NATIVE_INSTANCE_ID_LEN>(value, "invalid native process instance ID")
}

fn validate_nonzero_fixed<const LENGTH: usize>(
    value: &[u8],
    diagnostic: &'static str,
) -> Result<(), ControlError> {
    if value.len() != LENGTH || value.iter().all(|byte| *byte == 0) {
        return Err(ControlError::Invalid(diagnostic));
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn validate_signed_route_fields(
    reservation_id: &[u8],
    finalize_id: &[u8],
    auth_secret: &[u8],
    auth_commitment: &[u8],
    certificate_sha256: &[u8],
    client_native_instance_id: &[u8],
    exit_native_instance_id: &[u8],
) -> Result<(), ControlError> {
    validate_nonzero_fixed::<SIGNED_ID_LEN>(reservation_id, "invalid signed reservation ID")?;
    validate_nonzero_fixed::<SIGNED_ID_LEN>(finalize_id, "invalid signed finalize ID")?;
    validate_nonzero_fixed::<SHA256_LEN>(auth_commitment, "invalid authentication commitment")?;
    validate_nonzero_fixed::<SHA256_LEN>(certificate_sha256, "invalid certificate digest")?;
    validate_native_instance_id(client_native_instance_id)?;
    validate_native_instance_id(exit_native_instance_id)?;

    let mut hasher = Sha256::new();
    hasher.update(NATIVE_ROUTE_AUTH_COMMITMENT_DOMAIN);
    hasher.update(auth_secret);
    let expected: [u8; SHA256_LEN] = hasher.finalize().into();
    if auth_commitment != expected {
        return Err(ControlError::Invalid(
            "authentication bearer does not match signed commitment",
        ));
    }
    Ok(())
}

fn validate_tunnel_assignment(value: &TunnelAssignment) -> Result<(), ControlError> {
    if value.assigned_ipv4.len() != 4
        || value.assigned_ipv4.iter().all(|byte| *byte == 0)
        || value.assigned_prefix_v4 != 32
        || value.server_ipv4.len() != 4
        || value.server_ipv4.iter().all(|byte| *byte == 0)
        || value.assigned_ipv4 == value.server_ipv4
        || value.server_prefix_v4 != 32
        || !(1_280..=9_000).contains(&value.mtu)
    {
        return Err(ControlError::Invalid("invalid IPv4 tunnel assignment"));
    }
    if value.assigned_ipv6.is_empty() {
        if value.assigned_prefix_v6 != 0 {
            return Err(ControlError::Invalid("absent IPv6 assignment has a prefix"));
        }
    } else if value.assigned_ipv6.len() != 16
        || value.assigned_ipv6.iter().all(|byte| *byte == 0)
        || !(96..=126).contains(&value.assigned_prefix_v6)
    {
        return Err(ControlError::Invalid("invalid IPv6 tunnel assignment"));
    }
    Ok(())
}

fn validate_session_shape(
    minimum_paths: u32,
    masque_context_id: u64,
    transport_mode: i32,
) -> Result<(), ControlError> {
    validate_masque_context(masque_context_id)?;
    let mode = TransportMode::try_from(transport_mode)
        .map_err(|_| ControlError::Invalid("unknown transport mode"))?;
    match mode {
        TransportMode::MultipathQuic if (2..=8).contains(&minimum_paths) => Ok(()),
        TransportMode::SinglePathGeneralUdp if minimum_paths == 1 => Ok(()),
        TransportMode::Unspecified => Err(ControlError::Invalid("transport mode is required")),
        _ => Err(ControlError::Invalid(
            "path count does not match transport mode",
        )),
    }
}

fn validate_auth_secret(value: &[u8]) -> Result<(), ControlError> {
    if value.len() != AUTH_SECRET_LEN
        || !value
            .iter()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(*byte, b'_' | b'-'))
        || !value
            .last()
            .is_some_and(|byte| b"AEIMQUYcgkosw048".contains(byte))
    {
        return Err(ControlError::Invalid(
            "per-route auth credential must be canonical unpadded base64url for 32 bytes",
        ));
    }
    Ok(())
}

fn validate_tls_server_name(value: &[u8]) -> Result<(), ControlError> {
    if value.is_empty() || value.len() > MAX_TLS_SERVER_NAME {
        return Err(ControlError::Invalid("invalid TLS server name"));
    }
    for label in value.split(|byte| *byte == 46) {
        if label.is_empty()
            || label.len() > 63
            || !label[0].is_ascii_alphanumeric()
            || !label[label.len() - 1].is_ascii_alphanumeric()
            || !label
                .iter()
                .all(|byte| byte.is_ascii_alphanumeric() || *byte == 45)
        {
            return Err(ControlError::Invalid("invalid TLS server name"));
        }
    }
    Ok(())
}

fn validate_expiry(expires_at_ms: u64) -> Result<(), ControlError> {
    if expires_at_ms == 0 {
        return Err(ControlError::Invalid("authorization expiry is required"));
    }
    Ok(())
}

fn validate_context(value: &[u8]) -> Result<(), ControlError> {
    if value.len() != 16 || value.iter().all(|byte| *byte == 0) {
        return Err(ControlError::Invalid(
            "route context ID must be a non-zero 16-byte value",
        ));
    }
    Ok(())
}

pub(crate) fn validate_add_path(value: &AddPath) -> Result<(), ControlError> {
    const OVERLAY_PREFIX: [u8; 6] = [0xfd, 0x76, 0x6f, 0x6c, 0x70, 0x61];

    validate_context(&value.route_context_id)?;
    let valid_overlay = value.local_ip.len() == 16
        && value.remote_ip.len() == 16
        && value.local_ip.starts_with(&OVERLAY_PREFIX)
        && value.remote_ip.starts_with(&OVERLAY_PREFIX)
        && value.local_ip[..14] == value.remote_ip[..14]
        && u16::from_be_bytes([value.local_ip[10], value.local_ip[11]])
            == u16::try_from(value.path_id).unwrap_or(0)
        && u16::from_be_bytes([value.local_ip[14], value.local_ip[15]]) == 1
        && u16::from_be_bytes([value.remote_ip[14], value.remote_ip[15]]) == 4;
    if value.path_id == 0
        || value.path_id > 8
        || !valid_overlay
        || !(1..=65_535).contains(&value.local_port)
        || !(1..=65_535).contains(&value.remote_port)
        || value.reservation_hash.len() != 32
        || value.reservation_hash.iter().all(|byte| *byte == 0)
    {
        return Err(ControlError::Invalid(
            "AddPath must name one canonical client-to-exit overlay path",
        ));
    }
    Ok(())
}

pub(crate) fn validate_start_exit(value: &StartExitSession) -> Result<(), ControlError> {
    validate_context(&value.route_context_id)?;
    validate_session_shape(
        value.minimum_paths,
        value.masque_context_id,
        value.transport_mode,
    )?;
    if !matches!(
        TransportMode::try_from(value.transport_mode),
        Ok(TransportMode::SinglePathGeneralUdp)
    ) || value.minimum_paths != 1
    {
        return Err(ControlError::Invalid(
            "v6 exit listener supports exactly one general-UDP path",
        ));
    }
    validate_auth_secret(&value.auth_secret)?;
    validate_expiry(value.expires_at_ms)?;
    if value.exit_spki_sha256.len() != 32 || value.exit_spki_sha256.iter().all(|byte| *byte == 0) {
        return Err(ControlError::Invalid(
            "SPKI pin must be a non-zero 32-byte value",
        ));
    }
    validate_tls_server_name(&value.tls_server_name)?;
    validate_exit_overlay_tuple(value)?;
    validate_pem(
        &value.tls_certificate_pem,
        MAX_TLS_CERTIFICATE_PEM,
        "invalid in-memory TLS certificate",
    )?;
    validate_pem(
        &value.tls_private_key_pem,
        MAX_TLS_PRIVATE_KEY_PEM,
        "invalid in-memory TLS private key",
    )?;
    validate_signed_route_fields(
        &value.reservation_id,
        &value.finalize_id,
        &value.auth_secret,
        &value.auth_commitment,
        &value.certificate_sha256,
        &value.client_native_instance_id,
        &value.exit_native_instance_id,
    )?;
    Ok(())
}

fn validate_exit_overlay_tuple(value: &StartExitSession) -> Result<(), ControlError> {
    const OVERLAY_PREFIX: [u8; 6] = [0xfd, 0x76, 0x6f, 0x6c, 0x70, 0x61];

    let valid_overlay = value.listener_ip.len() == 16
        && value.expected_client_ip.len() == 16
        && value.listener_ip.starts_with(&OVERLAY_PREFIX)
        && value.expected_client_ip.starts_with(&OVERLAY_PREFIX)
        && value.listener_ip[..14] == value.expected_client_ip[..14]
        && u16::from_be_bytes([value.listener_ip[10], value.listener_ip[11]])
            == u16::try_from(value.path_id).unwrap_or(0)
        && u16::from_be_bytes([value.listener_ip[14], value.listener_ip[15]]) == 4
        && u16::from_be_bytes([value.expected_client_ip[14], value.expected_client_ip[15]]) == 1;
    if value.path_id == 0
        || value.path_id > 8
        || !valid_overlay
        || !(1..=65_535).contains(&value.listener_port)
        || !(1..=65_535).contains(&value.expected_client_port)
        || value.reservation_hash.len() != 32
        || value.reservation_hash.iter().all(|byte| *byte == 0)
    {
        return Err(ControlError::Invalid(
            "StartExitSession must name one canonical client-to-exit overlay listener",
        ));
    }
    Ok(())
}

fn validate_pem(
    value: &[u8],
    maximum: usize,
    diagnostic: &'static str,
) -> Result<(), ControlError> {
    if value.is_empty() || value.len() > maximum || value.contains(&0) {
        return Err(ControlError::Invalid(diagnostic));
    }
    Ok(())
}

fn validate_masque_context(value: u64) -> Result<(), ControlError> {
    if value == 0 || value > MAX_MASQUE_CONTEXT_ID {
        return Err(ControlError::Invalid(
            "MASQUE context ID must be a non-zero 62-bit value",
        ));
    }
    Ok(())
}

fn validate_ip_packet(packet: &[u8]) -> Result<(), ControlError> {
    if packet.len() < 20 || packet.len() > MAX_INNER_PACKET {
        return Err(ControlError::Invalid("invalid inner IP datagram length"));
    }
    match packet[0] >> 4 {
        4 => {
            let header_len = usize::from(packet[0] & 0x0f) * 4;
            let total_len = usize::from(u16::from_be_bytes([packet[2], packet[3]]));
            if header_len < 20 || header_len > packet.len() || total_len != packet.len() {
                return Err(ControlError::Invalid("malformed IPv4 datagram"));
            }
        }
        6 => {
            if packet.len() < 40 {
                return Err(ControlError::Invalid("truncated IPv6 datagram"));
            }
            let payload_len = usize::from(u16::from_be_bytes([packet[4], packet[5]]));
            if payload_len == 0 || payload_len + 40 != packet.len() {
                return Err(ControlError::Invalid("malformed IPv6 datagram"));
            }
        }
        _ => return Err(ControlError::Invalid("inner datagram is not IPv4/IPv6")),
    }
    Ok(())
}

