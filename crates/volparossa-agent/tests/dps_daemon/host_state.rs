//! Private, read-only observations around one explicitly requested hosted proof.

use std::{collections::BTreeMap, fs, path::Path, process::Stdio, time::Duration};

use serde_json::Value;
use tokio::{io::AsyncReadExt, process::Command, time::timeout};

const LIMIT: u64 = 4 * 1024 * 1024;

// Storage route-retirement's reviewed normalizer, retaining the backend label.
// Literal legacy producer headers are additionally recognized. Unrecognized
// headers and incomplete/ambiguous producer output are rejected, never erased.
const FIREWALL_NORMALIZER: &str = r##"
BEGIN {
  ctime = "(Sun|Mon|Tue|Wed|Thu|Fri|Sat) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) ( [1-9]|[12][0-9]|3[01]) ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9] [0-9][0-9][0-9][0-9]"
}
{
  quoted = 0
  escaped = 0
  for (i = 1; i <= length($0); i++) {
    character = substr($0, i, 1)
    if (escaped) { escaped = 0; continue }
    if (character == "\\") { escaped = 1; continue }
    if (character == "\"") quoted = !quoted
  }
  if (quoted || escaped) { failed = 1; exit 1 }
}
$0 ~ ("^# Generated by ip(6)?tables-save v[0-9][0-9A-Za-z.+:~_-]*( \\((nf_tables|legacy)\\))? on " ctime "$") {
  generated++
  sub(/ on .*$/, " on [timestamp]")
}
/^# Generated by / && $0 !~ / on \[timestamp\]$/ { failed = 1; exit 1 }
$0 ~ ("^# Completed on " ctime "$") {
  completed++
  $0 = "# Completed on [timestamp]"
}
/^# Completed on / && $0 != "# Completed on [timestamp]" { failed = 1; exit 1 }
/^:[-A-Za-z0-9_.+]+ (ACCEPT|DROP|-) \[[0-9]+:[0-9]+\]$/ {
  sub(/ \[[0-9]+:[0-9]+\]$/, " [counters]")
}
{ print }
END { if (failed || generated != completed) exit 1 }
"##;

/// Snapshot contents deliberately have no Debug/Serialize implementation.
#[derive(PartialEq, Eq)]
pub(super) struct HostState {
    pub(super) routes: Vec<Value>,
    pub(super) dns: Vec<Vec<u8>>,
    pub(super) firewall: Vec<Vec<u8>>,
    pub(super) sysctls: BTreeMap<&'static str, Vec<u8>>,
    pub(super) namespace: std::path::PathBuf,
}

/// Capture both streams with independent bounds; no subprocess output is logged.
pub(super) async fn capture_command(
    command: &mut Command,
    seconds: u64,
) -> Result<(bool, Vec<u8>), &'static str> {
    let mut child = command
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .kill_on_drop(true)
        .spawn()
        .map_err(|_| "command_spawn")?;
    let (Some(stdout), Some(stderr)) = (child.stdout.take(), child.stderr.take()) else {
        let _ = child.start_kill();
        let _ = timeout(Duration::from_secs(5), child.wait()).await;
        return Err("command_streams");
    };
    let collected = timeout(Duration::from_secs(seconds), async {
        let (out, err) = tokio::join!(bounded(stdout), bounded(stderr));
        let status = child.wait().await.map_err(|_| "command_wait")?;
        let output = out?;
        let _ = err?;
        Ok((status.success(), output))
    })
    .await;
    match collected {
        Ok(Ok(result)) => Ok(result),
        failure => {
            let _ = child.start_kill();
            let _ = timeout(Duration::from_secs(5), child.wait()).await;
            Err(match failure {
                Ok(Err(code)) => code,
                _ => "command_timeout",
            })
        }
    }
}

async fn bounded(reader: impl tokio::io::AsyncRead + Unpin) -> Result<Vec<u8>, &'static str> {
    let mut output = Vec::new();
    reader
        .take(LIMIT + 1)
        .read_to_end(&mut output)
        .await
        .map_err(|_| "command_read")?;
    if output.len() > usize::try_from(LIMIT).expect("small limit") {
        return Err("command_output_bound");
    }
    Ok(output)
}

async fn observation(program: &str, args: &[&str]) -> Result<Vec<u8>, &'static str> {
    let (success, output) = capture_command(Command::new(program).args(args), 10).await?;
    if !success {
        return Err("observation_failed");
    }
    Ok(output)
}

fn private_read(path: &Path, maximum: u64) -> Result<Vec<u8>, &'static str> {
    use std::io::Read;
    let file = fs::File::open(path).map_err(|_| "observation_file")?;
    let mut bytes = Vec::new();
    file.take(maximum + 1)
        .read_to_end(&mut bytes)
        .map_err(|_| "observation_read")?;
    if u64::try_from(bytes.len()).map_err(|_| "observation_bound")? > maximum {
        return Err("observation_bound");
    }
    Ok(bytes)
}

fn canonical_records(raw: &[u8]) -> Result<Value, &'static str> {
    let mut value: Value = serde_json::from_slice(raw).map_err(|_| "observation_json")?;
    let rows = value.as_array_mut().ok_or("observation_array")?;
    rows.sort_by_cached_key(Value::to_string);
    Ok(value)
}

fn dns_configuration() -> Result<Vec<Vec<u8>>, &'static str> {
    use std::os::unix::fs::MetadataExt;
    let resolver = Path::new("/etc/resolv.conf");
    let first = fs::symlink_metadata(resolver).map_err(|_| "dns_metadata")?;
    let target = if first.file_type().is_symlink() {
        fs::read_link(resolver)
            .map_err(|_| "dns_symlink")?
            .as_os_str()
            .as_encoded_bytes()
            .to_vec()
    } else if first.is_file() {
        Vec::new()
    } else {
        return Err("dns_type");
    };
    let bytes = private_read(resolver, 65_536)?;
    let last = fs::symlink_metadata(resolver).map_err(|_| "dns_metadata")?;
    let identity = |metadata: &fs::Metadata| {
        format!(
            "{}:{}:{}:{}:{}:{}:{}:{}:{}",
            metadata.dev(),
            metadata.ino(),
            metadata.mode(),
            metadata.uid(),
            metadata.gid(),
            metadata.nlink(),
            metadata.len(),
            metadata.mtime(),
            metadata.mtime_nsec()
        )
        .into_bytes()
    };
    if identity(&first) != identity(&last) {
        return Err("dns_changed_during_capture");
    }
    Ok(vec![bytes, target, identity(&first)])
}

fn nft_configuration(raw: &[u8]) -> Result<Vec<u8>, &'static str> {
    let mut value: Value = serde_json::from_slice(raw).map_err(|_| "firewall_json")?;
    let object = value.as_object_mut().ok_or("firewall_object")?;
    if object.len() != 1 {
        return Err("firewall_shape");
    }
    let rows = object
        .get_mut("nftables")
        .and_then(Value::as_array_mut)
        .ok_or("firewall_array")?;
    if rows
        .iter()
        .any(|row| row.as_object().is_none_or(|map| map.len() != 1))
    {
        return Err("firewall_entry");
    }
    rows.retain(|row| row.get("metainfo").is_none());
    serde_json::to_vec(&value).map_err(|_| "firewall_encoding")
}

async fn legacy_configuration(raw: &[u8]) -> Result<Vec<u8>, &'static str> {
    // awk receives only this fixed normalizer and a private bounded input file.
    use std::io::Write;
    let mut input = tempfile::NamedTempFile::new().map_err(|_| "firewall_temporary")?;
    input.write_all(raw).map_err(|_| "firewall_write")?;
    let mut command = Command::new("awk");
    command
        .env("LC_ALL", "C")
        .arg(FIREWALL_NORMALIZER)
        .arg(input.path());
    let (success, output) = capture_command(&mut command, 5).await?;
    if !success {
        return Err("firewall_normalization");
    }
    Ok(output)
}

impl HostState {
    pub(super) async fn capture() -> Result<Self, &'static str> {
        let mut routes = Vec::new();
        for family in ["-4", "-6"] {
            for args in [
                vec![family, "-j", "route", "show", "table", "all"],
                vec![family, "-j", "rule", "show"],
            ] {
                routes.push(canonical_records(&observation("ip", &args).await?)?);
            }
        }
        let dns = dns_configuration()?;
        let mut firewall = vec![nft_configuration(
            &observation(
                "sudo",
                &["-n", "nft", "--stateless", "-j", "list", "ruleset"],
            )
            .await?,
        )?];
        for program in ["iptables-legacy-save", "ip6tables-legacy-save"] {
            firewall.push(
                legacy_configuration(
                    &observation("sudo", &["-n", "env", "LC_ALL=C", program]).await?,
                )
                .await?,
            );
        }
        let mut sysctls = BTreeMap::new();
        for path in [
            "/proc/sys/net/ipv4/ip_forward",
            "/proc/sys/net/ipv4/conf/all/forwarding",
            "/proc/sys/net/ipv4/conf/all/src_valid_mark",
            "/proc/sys/net/ipv6/conf/all/forwarding",
        ] {
            sysctls.insert(path, private_read(Path::new(path), 64)?);
        }
        Ok(Self {
            routes,
            dns,
            firewall,
            sysctls,
            namespace: fs::read_link("/proc/self/ns/net").map_err(|_| "namespace_read")?,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn command_capture_bounds_both_streams_and_joins_timed_out_child() {
        for stream in ["stdout", "stderr"] {
            let mut command = Command::new("python3");
            command.args([
                "-I",
                "-B",
                "-c",
                &format!("import sys; sys.{stream}.buffer.write(b'x' * (4 * 1024 * 1024 + 1))"),
            ]);
            assert_eq!(
                capture_command(&mut command, 5).await,
                Err("command_output_bound")
            );
        }
        let root = tempfile::tempdir().unwrap();
        let pidfile = root.path().join("child.pid");
        let mut command = Command::new("python3");
        command.args(["-I", "-B", "-c", "import os,pathlib,sys,time; pathlib.Path(sys.argv[1]).write_text(str(os.getpid())); time.sleep(60)"]).arg(&pidfile);
        assert_eq!(
            capture_command(&mut command, 1).await,
            Err("command_timeout")
        );
        let pid = fs::read_to_string(pidfile).unwrap();
        assert!(pid.bytes().all(|byte| byte.is_ascii_digit()));
        assert!(
            !Path::new("/proc").join(pid).exists(),
            "timed-out child must be reaped"
        );
    }

    #[test]
    fn nft_normalization_preserves_policy_and_ignores_only_metainfo() {
        let first =
            br#"{"nftables":[{"metainfo":{"version":"a"}},{"rule":{"expr":[{"drop":null}]}}]}"#;
        let changed_version =
            br#"{"nftables":[{"metainfo":{"version":"b"}},{"rule":{"expr":[{"drop":null}]}}]}"#;
        let changed_rule = br#"{"nftables":[{"rule":{"expr":[{"accept":null}]}}]}"#;
        assert_eq!(
            nft_configuration(first).unwrap(),
            nft_configuration(changed_version).unwrap()
        );
        assert_ne!(
            nft_configuration(first).unwrap(),
            nft_configuration(changed_rule).unwrap()
        );
        assert!(nft_configuration(br#"{"nftables":[{"rule":{},"metainfo":{}}]}"#).is_err());
        assert!(nft_configuration(br#"{"nftables":null}"#).is_err());
    }

    #[tokio::test]
    async fn firewall_normalization_keeps_semantic_changes_and_rejects_ambiguity() {
        for producer in ["iptables-save", "ip6tables-save"] {
            for backend in ["", " (nf_tables)", " (legacy)"] {
                let before = format!(
                    "# Generated by {producer} v1.8.10{backend} on Thu Oct 15 10:10:10 2026\n*filter\n:INPUT ACCEPT [1:2]\n:custom-chain - [3:4]\n-A INPUT -m comment --comment \"semantic [1:2]\" -j custom-chain\nCOMMIT\n# Completed on Thu Oct 15 10:10:10 2026\n"
                );
                let after = before
                    .replace("10:10:10", "11:11:11")
                    .replace("ACCEPT [1:2]", "ACCEPT [99:100]")
                    .replace("- [3:4]", "- [101:102]");
                let normalized = legacy_configuration(before.as_bytes()).await.unwrap();
                assert_eq!(
                    normalized,
                    legacy_configuration(after.as_bytes()).await.unwrap()
                );
                for (old, new) in [
                    ("ACCEPT", "DROP"),
                    ("custom-chain", "other-chain"),
                    ("semantic [1:2]", "semantic [9:10]"),
                    ("*filter", "*nat"),
                    ("v1.8.10", "v1.8.11"),
                    ("COMMIT\n", ""),
                    ("v1.8.10", "v1.8.10 (other_backend)"),
                ] {
                    let changed = legacy_configuration(before.replace(old, new).as_bytes()).await;
                    assert!(changed.is_err() || changed.unwrap() != normalized);
                }
                let different_backend =
                    before.replace(&format!("v1.8.10{backend} on"), "v1.8.10 (legacy) on");
                if backend != " (legacy)" {
                    assert_ne!(
                        normalized,
                        legacy_configuration(different_backend.as_bytes())
                            .await
                            .unwrap()
                    );
                }
                for embedded in [
                    "# Completed on Thu Oct 15 10:10:10 2026",
                    ":INPUT ACCEPT [1:2]",
                ] {
                    assert!(
                        legacy_configuration(
                            before
                                .replace("semantic [1:2]", &format!("first\n{embedded}\nlast"))
                                .as_bytes()
                        )
                        .await
                        .is_err()
                    );
                }
                assert!(
                    legacy_configuration(
                        before
                            .replace("10:10:10", "unrecognized-timestamp")
                            .as_bytes()
                    )
                    .await
                    .is_err()
                );
            }
        }
        assert_ne!(
            legacy_configuration(b"").await.unwrap(),
            legacy_configuration(b"*filter\nCOMMIT\n").await.unwrap()
        );
    }
}
